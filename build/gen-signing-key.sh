#!/usr/bin/env bash
set -euo pipefail

# One-time: creates the release signing key pair.
# - Private key: $TINYSHELL_SIGNING_KEY (default ~/.config/tinyshell/release-signing-key.pem).
#   Never commit it. Back it up offline: without it you cannot ship updates to installed
#   copies; if it leaks, anyone can.
# - Public key: keys/release-public.pem and src/release_key.h (commit both).
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"
KEY="${TINYSHELL_SIGNING_KEY:-$HOME/.config/tinyshell/release-signing-key.pem}"
if [[ -e "$KEY" ]]; then
  echo "Ya existe $KEY; no la sobrescribo. Para regenerar solo el lado público:" >&2
  echo "  REGEN_PUBLIC=1 $0" >&2
  [[ "${REGEN_PUBLIC:-}" == 1 ]] || exit 1
else
  mkdir -p "$(dirname "$KEY")"
  (umask 077 && openssl genpkey -algorithm RSA -pkeyopt rsa_keygen_bits:3072 -out "$KEY" 2>/dev/null)
  echo "Clave privada: $KEY (hacé un backup offline)"
fi
mkdir -p keys
openssl pkey -in "$KEY" -pubout -out keys/release-public.pem
{
  echo "/* Public half of the release signing key (DER SubjectPublicKeyInfo)."
  echo " * Generated by build/gen-signing-key.sh; the private key never enters the repo. */"
  echo "#ifndef TINYSHELL_RELEASE_KEY_H"
  echo "#define TINYSHELL_RELEASE_KEY_H"
  echo
  echo "static const unsigned char RELEASE_PUBLIC_KEY[] = {"
  openssl pkey -in "$KEY" -pubout -outform DER | od -An -v -tx1 |
    sed -E 's/ *([0-9a-f]{2})/0x\1, /g; s/, $/,/; s/^/    /'
  echo "};"
  echo "#define RELEASE_PUBLIC_KEY_LEN sizeof(RELEASE_PUBLIC_KEY)"
  echo
  echo "#endif"
} >src/release_key.h
echo "Clave pública: keys/release-public.pem y src/release_key.h (commitealas)."
