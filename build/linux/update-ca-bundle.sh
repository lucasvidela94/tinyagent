#!/usr/bin/env bash
set -euo pipefail

# Regenerates src/platform/posix/ca_bundle.c: Mozilla's root certificates as published by
# curl (https://curl.se/docs/caextract.html), pinned by date and SHA-256. The Linux build
# trusts these plus the system's bundle, so an old distro with expired roots still connects.
#   build/linux/update-ca-bundle.sh 2026-09-25 <sha256>   (both from the curl page)
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
DATE="${1:?usage: update-ca-bundle.sh YYYY-MM-DD SHA256}"
SHA="${2:?missing the published SHA-256}"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
curl -fsSL -o "$TMP/cacert.pem" "https://curl.se/ca/cacert-$DATE.pem"
echo "$SHA  $TMP/cacert.pem" | sha256sum -c -
OUT="$ROOT/src/platform/posix/ca_bundle.c"
{
  echo "/* GENERATED by build/linux/update-ca-bundle.sh from https://curl.se/ca/cacert-$DATE.pem"
  echo " * (SHA-256 $SHA). Do not edit: rerun the script to update the roots. */"
  echo '#include "ca_bundle.h"'
  echo
  echo 'const char *const CA_BUNDLE[] = {'
  awk '
    /-----BEGIN CERTIFICATE-----/ { cert = ""; on = 1 }
    on { cert = cert "    \"" $0 "\\n\"\n"; len += length($0) + 1 }
    /-----END CERTIFICATE-----/ {
      on = 0
      if (len > 4000) { print "certificate too long for a C99 string literal" > "/dev/stderr"; exit 1 }
      printf "%s", cert; print "    ,"; len = 0; n++
    }
    END { if (n < 50) { print "too few certificates: " n > "/dev/stderr"; exit 1 } }
  ' "$TMP/cacert.pem"
  echo '};'
  echo
  echo 'const int CA_BUNDLE_COUNT = (int)(sizeof CA_BUNDLE / sizeof CA_BUNDLE[0]);'
} >"$OUT"
echo "Wrote $OUT ($(grep -c 'BEGIN CERT' "$OUT") certificates from $DATE)"
